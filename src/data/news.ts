export function getAllArticles(): NewsArticle[] {
  return [...newsArticles].sort(
    (a, b) => new Date(b.publishedAt).getTime() - new Date(a.publishedAt).getTime()
  );
}

export function getArticleBySlug(slug: string): NewsArticle | undefined {
  return newsArticles.find((article) => article.slug === slug);
}

export function getBreakingNews(): NewsArticle[] {
  return newsArticles.filter((article) => article.isBreaking);
}

export function getFeaturedNews(): NewsArticle[] {
  return newsArticles.filter((article) => article.isFeatured);
}

export function getRelatedArticles(current: NewsArticle, limit = 3): NewsArticle[] {
  return newsArticles
    .filter(
      (article) =>
        article.slug !== current.slug && article.category === current.category
    )
    .slice(0, limit);
}
